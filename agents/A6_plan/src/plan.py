def add(f, k, name, cat, g, w='', nrm=None, seats=None, open=False, short=None, row=None):
    g = g.intersection(LP).difference(TAKEN[f])
    g = clean(g, 0.15)
    if g.is_empty or g.area < 1:
        print('!! empty', f, k)
        return None
    TAKEN[f] = TAKEN[f].union(g)
    r = dict(f=f, k=k, n=name, c=cat, g=g, w=w, nrm=nrm, seats=seats, open=open, s=short or name, row=row or cat)
    ROOMS.append(r)
    return r


