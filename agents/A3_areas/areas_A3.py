     (r'^avan', 'Место ожидания у выдачи абонементов' if r['f'] == '1' else 'Аванзал этажа (2–4 эт.)', 'avan', 1.5),
     (r'^cat$', 'Читательские каталоги', 'cat', None),
     (r'^sbo', 'Справочно-библиографический отдел', 'cat', None),
     (r'^oa', 'Открытый доступ', 'store:oa', None),
     (r'^vyd', 'Пункт выдачи и рабочие места сотрудников хранения', 'store:staff', None),
     (r'^comp', 'Компактное хранение', 'store:comp', None),
     (r'^(st[WE]|bst|per)', 'Основное книгохранилище (отсек)', 'store:main', None),
     (r'^mba', 'МБА', 'serv:mba', None),
     (r'^(proc|exped)', 'Комплектование и обработка, экспедиция', 'serv:proc', None),
     (r'^scat', 'Служебный каталог', 'serv:scat', None),
     (r'^(copy|rest)', 'Лаборатория (копирование, реставрация)', 'serv:lab', None),
     (r'^(svc\d|svc$|dir|staffin|staffE)', 'Служебно-производственные, дирекция, персонал', 'serv:sp', None),
     (r'^bags', 'Хранение портфелей', 'serv:bags', None),
     (r'^lect', 'Лекционный зал', 'x', 'fix150'),
