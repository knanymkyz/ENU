for nm, n, m in [('Учебные залы (40 % М)', 720, mU), ('Научные залы', 900, mS), ('АВ-залы и редкие книги', 180, mA)]:
    w(f'| {nm} | {fi(n)} | {fi(m)} | {round(100*m/n)} |')
