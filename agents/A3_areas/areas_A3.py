     (r'^guard', 'Пожарный пост и охрана', 'x', None),
     (r'^brhall', 'Холл перехода (резерв)', 'x', None),
     (r'^sz', 'Зона безопасности МГН', 'x', None),
     (r'^(pk|hallK|hallSW|lh)', 'Карманы, холлы, лифтовые холлы', 'cor', None),
     (r'^(ring|svc[NEL]|bcor|bspur)', 'Коридоры', 'cor', None),
