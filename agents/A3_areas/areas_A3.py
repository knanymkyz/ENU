 'Абонемент (зона читателей)','Место ожидания у выдачи абонементов','Аванзал этажа (2–4 эт.)','Читательские каталоги','Справочно-библиографический отдел','Лекционный зал','Буфет и зона отдыха','Гардероб читателей (1 860 мест)',
 'Открытый доступ','Пункт выдачи и рабочие места сотрудников хранения','Основное книгохранилище (отсек)','Компактное хранение','Хранилище редких книг','Фонд АВ-материалов и аппаратная','Фонд и кладовая абонемента',
 'МБА','Комплектование и обработка, экспедиция','Служебный каталог','Лаборатория (копирование, реставрация)','Служебно-производственные, дирекция, персонал','Хранение портфелей',
