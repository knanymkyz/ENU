w('- Места каждого зала посчитаны с округлением вниз, поэтому сумма может быть на 1–3 меньше, чем в отчёте А3 (там делилась общая площадь).')
w('- В отчёте А3 для АВ-залов в счёт шли и фонд АВ, и хранилище редких книг (132 места); здесь места — только в залах.')
w('')
