w('## 3. Перечень помещений: количество, площадь, места')
w('')
w('| Помещение | Кол-во | Этажи | Площадь одного, м² | Всего по плану, м² | Мест (чел.) |')
w('|---|---:|---|---|---:|---:|')
G = collections.OrderedDict()
for r in rooms.values():
    g = G.setdefault(r['t'], dict(n=0, fl=set(), a=[], m=0, hm=False))
    g['n'] += 1; g['fl'].add(r['f']); g['a'].append(r['a'])
    if r['m'] is not None: g['m'] += r['m']; g['hm'] = True
